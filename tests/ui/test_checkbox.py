from playwright.sync_api import Page


def test_checkbox_visibility(page: Page):
    # 1. Переходим на страницу
    page.goto("https://demoqa.com/checkbox")

    # Создаем локаторы для текста (так проще читать код)
    home_label = page.locator("text=Home")
    desktop_label = page.locator("text=Desktop")

    # ==========================================================
    # ПУНКТ 1: Проверка начального состояния
    # ==========================================================

    # "Home" должен быть виден сразу
    assert home_label.is_visible() is True, "Home должен быть видим!"

    # "Desktop" НЕ должен быть виден (он скрыт внутри свернутого списка)
    # is_hidden() возвращает True, если элемента нет на экране или он в DOM с display:none
    assert desktop_label.is_hidden() is True, "Desktop должен быть скрыт!"

    # ==========================================================
    # ПУНКТ 2: Раскрываем список (кликаем по стрелочке/тогглу)
    # ==========================================================

    # Нам нужно кликнуть именно по стрелочке (переключателю) у Home.
    # В HTML это элемент с классом 'rct-tree-switcher'.
    # Берем первый такой элемент (он принадлежит Home)
    page.locator("span.rc-tree-switcher").first.click()

    # ==========================================================
    # ПУНКТ 3: Проверка конечного состояния
    # ==========================================================

    # Теперь "Desktop" должен стать видимым
    assert desktop_label.is_visible() is True, "Desktop должен стать видимым после раскрытия!"

    print("✅ Все проверки видимости пройдены успешно!")