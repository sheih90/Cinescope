from playwright.sync_api import Page

def test_visible_after_5_seconds(page: Page):
    # 1. Переходим на страницу
    page.goto("https://demoqa.com/dynamic-properties")

    # Создаем локатор для кнопки "Visible After 5 Seconds"
    # По HTML (скриншот) её id = visibleAfter
    target_button = page.locator("#visibleAfter")

    # ==========================================================
    # ПУНКТ 1: Убеждаемся, что элемента нет
    # ==========================================================
    # is_hidden() возвращает True, если элемент не виден или его нет в коде страницы
    assert target_button.is_hidden() is True, "Кнопка должна быть скрыта в начале!"

    # ==========================================================
    # ПУНКТ 2: Ждем появления элемента
    # ==========================================================
    # page.wait_for_selector останавливает выполнение теста и ждет,
    # пока элемент не появится на экране (по умолчанию до 30 сек)
    page.wait_for_selector("#visibleAfter", state="visible")

    # ==========================================================
    # ПУНКТ 3: Проверяем финальное состояние
    # ==========================================================
    # Теперь элемент должен быть виден
    assert target_button.is_visible() is True, "Кнопка должна появиться!"

    # Для проверки кликаем по ней (опционально, но полезно)
    target_button.click()

    print("✅ Тест пройден! Кнопка успешно появилась и нажалась.")